// Writes lab/icons.js from pixl.json: the icons Export all writes to raw-icons/ (exported icons on
// icon artboards; pictogram artboards and drafts never), each as rows of cells, '.' empty and the
// fill's ladder level (0-8) otherwise. Icons are drawn in the ladder only; any other fill counts as 8.
// Run: node lab/build-icons.mjs
import fs from 'node:fs';
const pixl = JSON.parse(fs.readFileSync(new URL('../pixl.json', import.meta.url)));
// The editor's isExported and kindOf (editor/src/model/types.ts), for the icons kind.
const isPictogramBoard = a => a.kind === 'pictograms' || a.kind === 'illustrations';
const isExported = (a, ic) => a.export !== false && ic.export === true && !ic.instance;
const icons = {};
for (const board of pixl.artboards.filter(a => !isPictogramBoard(a))) {
  for (const icon of board.icons.filter(ic => isExported(board, ic))) {
    const grid = Array.from({ length: icon.h }, () => Array(icon.w).fill('.'));
    for (const r of icon.rects) {
      const level = /^lv(\d)$/.exec(r.fill ?? '')?.[1] ?? '8';
      for (let y = r.y; y < r.y + r.h; y++)
        for (let x = r.x; x < r.x + r.w; x++)
          if (y >= 0 && y < icon.h && x >= 0 && x < icon.w) grid[y][x] = level;
    }
    icons[icon.name] ??= { board: board.name, w: icon.w, h: icon.h, rows: grid.map(r => r.join('')) };
  }
}
fs.writeFileSync(new URL('./icons.js', import.meta.url),
  '// Generated by lab/build-icons.mjs from pixl.json. Do not edit by hand.\nwindow.PIXL_ICONS = ' + JSON.stringify(icons) + ';\n');
console.log(Object.keys(icons).length, 'icons');
