// Document color library: named colors with a light value and an optional dark value.
// Pixels reference a library color as `c:<id>`, so changing the color updates every pixel using it.
import type { ColorToken, Doc, Fill } from './types';

export const colorRef = (id: string): Fill => `c:${id}`;
export const isColorRef = (f: Fill) => f.startsWith('c:');
export const colorIdOf = (f: Fill) => (isColorRef(f) ? f.slice(2) : null);

/** CSS-safe slug of a color name: "Yellow faint" -> "yellow-faint". */
export const slugOf = (name: string) =>
  name.toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

/** Exported CSS variable name for a color. */
export const cssVarOf = (c: ColorToken) => `--pixl-${slugOf(c.name) || c.id}`;
/** Variable used inside the editor (by id, so renames never break rendering). */
export const editorVarOf = (id: string) => `--pixlc-${id}`;

export const findColor = (doc: Doc, id: string | null) => (id ? doc.colors?.find((c) => c.id === id) : undefined);

/** Problems with a color's name: empty, or a slug that collides with another color. */
export function nameProblem(doc: Doc, c: ColorToken): string | null {
  const slug = slugOf(c.name);
  if (!slug) return 'Name needs letters or digits';
  const clash = (doc.colors ?? []).find((o) => o.id !== c.id && slugOf(o.name) === slug);
  return clash ? `Same variable as "${clash.name}"` : null;
}

/** Is this value a link to another color? */
export const isLink = (v?: string) => !!v && v.startsWith('c:');
/** The value a color stores for a mode, before following links. Without a dark value, dark is the light one. */
export const rawOf = (c: ColorToken, mode: 'light' | 'dark') => (mode === 'dark' ? c.dark ?? c.light : c.light);
/** A color's hex in one mode, following links (each to the linked color as it looks in that mode). */
export function resolveColor(colors: ColorToken[] = [], c: ColorToken, mode: 'light' | 'dark', seen = new Set<string>()): string {
  const raw = rawOf(c, mode);
  if (!isLink(raw)) return raw;
  if (seen.has(c.id)) return '#000000'; // a loop: show something rather than hang
  seen.add(c.id);
  const t = colors.find((x) => x.id === raw.slice(2));
  return t ? resolveColor(colors, t, mode, seen) : '#000000';
}
/** Does this color look different in dark mode, once links are followed? */
export const differsByMode = (colors: ColorToken[] = [], c: ColorToken) => resolveColor(colors, c, 'light') !== resolveColor(colors, c, 'dark');
/** Colors that link, directly or not, to `id`: linking `id` to one of them would make a loop. */
export function linksTo(colors: ColorToken[], id: string): Set<string> {
  const out = new Set<string>([id]);
  for (let grew = true; grew;) {
    grew = false;
    for (const c of colors) if (!out.has(c.id) && [c.light, c.dark].some((v) => isLink(v) && out.has(v!.slice(2)))) { out.add(c.id); grew = true; }
  }
  return out;
}

/** Stylesheet for the editor: light values by default, dark values under the dark theme class. A link is
 *  written as the linked color's variable, so it follows that color in each mode. */
export function editorColorCss(colors: ColorToken[] = []): string {
  if (!colors.length) return '';
  const val = (v: string) => (isLink(v) ? `var(${editorVarOf(v.slice(2))})` : v);
  const light = colors.map((c) => `${editorVarOf(c.id)}: ${val(c.light)};`).join(' ');
  const dark = colors.map((c) => `${editorVarOf(c.id)}: ${val(rawOf(c, 'dark'))};`).join(' ');
  return `html { ${light} }\nhtml.theme-dark { ${dark} }\n`;
}

/** colors.css shipped with the package. Dark values follow prefers-color-scheme, like systm. */
export function exportColorCss(colors: ColorToken[] = []): string {
  const head = '/* Generated by Pixl Editor from pixl.json. Do not edit by hand. */\n';
  if (!colors.length) return head;
  const val = (v: string) => { if (!isLink(v)) return v; const t = colors.find((x) => x.id === v.slice(2)); return t ? `var(${cssVarOf(t)})` : '#000000'; };
  const light = colors.map((c) => `  ${cssVarOf(c)}: ${val(c.light)};`).join('\n');
  // only colors with their own dark value need a dark rule: a link already follows its color into dark mode
  const darkOnes = colors.filter((c) => c.dark && c.dark !== c.light);
  const dark = darkOnes.length ? `\n@media (prefers-color-scheme: dark) {\n  :root {\n${darkOnes.map((c) => `    ${cssVarOf(c)}: ${val(c.dark!)};`).join('\n')}\n  }\n}\n` : '';
  return `${head}:root {\n${light}\n}\n${dark}`;
}

/** Ids of every rect and text using a fill, across the document. */
export function idsUsing(doc: Doc, fill: Fill): string[] {
  const ids: string[] = [];
  for (const a of doc.artboards) {
    for (const r of a.rects) if (r.fill === fill) ids.push(r.id);
    for (const t of a.texts ?? []) if (t.fill === fill) ids.push(t.id);
    for (const ic of a.icons) for (const r of ic.rects) if (r.fill === fill) ids.push(r.id);
  }
  return ids;
}

/** Count rects and texts using a fill. Texts count too: deleting a color recolors them as well. */
export const usageOf = (doc: Doc, fill: Fill): number => idsUsing(doc, fill).length;

/** What a color follows, for a tooltip: "light → red 50 · dark → red 900", or '' when it holds its own values. */
export function linkSummary(colors: ColorToken[], c: ColorToken): string {
  const name = (v?: string) => colors.find((x) => x.id === v?.slice(2))?.name ?? 'missing color';
  const parts: string[] = [];
  if (isLink(c.light)) parts.push(`light → ${name(c.light)}`);
  if (c.dark !== undefined ? isLink(c.dark) : isLink(c.light)) parts.push(`dark → ${name(c.dark ?? c.light)}`);
  return parts.join(' · ');
}
/** Colors whose light or dark value links straight to `id`. */
export const linkedFrom = (colors: ColorToken[], id: string) => colors.filter((c) => c.light === `c:${id}` || c.dark === `c:${id}`);
